#!/usr/bin/env python3
"""Generate protocol limits shared by the Lua client and the Python source."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    schema = json.loads((ROOT / 'shared/protocol/schema/music/v1.json').read_text())
    definitions = schema['$defs']
    http = schema['x-http']
    limits = {key + '_length': definitions[key]['maxLength'] for key in ('id', 'title', 'artist', 'album', 'art', 'query', 'url')}
    limits.update(browse_path=http['browse'], max_duration_ms=definitions['durationMs']['maximum'], search_path=http['search'], resolve_path=http['resolve'], max_body=http['maxBody'], timeout_ms=http['timeoutMs'],
                  max_tracks=definitions['search']['properties']['tracks']['maxItems'])
    assert limits['max_tracks'] == definitions['resolve']['properties']['links']['maxItems']
    outputs = {
        'plugins/player/online_contract.lua': '-- Generated by tools/music-source/gen_contract.py\nreturn {\n' +
        ''.join(f'  {key} = {json.dumps(value)},\n' for key, value in limits.items()) + '}\n',
        'tools/music-source/contract.py': '# Generated by tools/music-source/gen_contract.py\n' +
        ''.join(f'{key.upper()} = {value!r}\n' for key, value in limits.items()),
    }
    for path, data in outputs.items():
        target = ROOT / path
        if args.check:
            if not target.exists() or target.read_text() != data:
                parser.error(f'out of date: {path}')
        else:
            target.write_text(data)


if __name__ == '__main__':
    main()
