#!/usr/bin/env python3
"""Generate independent UTC season-boundary vectors with PyEphem/libastro.

Run with an isolated Python environment containing ephem==4.2.1:
    /tmp/thinkos-venv/astro/bin/python -I tools/gen_seasons_golden.py

The generator never imports or reimplements the device's Meeus polynomials.
PyEphem next_equinox/next_solstice supply the four roots independently.
Reference: https://rhodesmill.org/pyephem/quick.html#equinoxes-solstices
"""

import argparse
import datetime
from pathlib import Path

import ephem


def epoch_millis(instant):
    return round(instant.datetime().replace(tzinfo=datetime.timezone.utc).timestamp() * 1000)


def generate():
    if ephem.__version__ != "4.2.1":
        raise SystemExit(f"expected ephem 4.2.1, found {ephem.__version__}")
    lines = [
        "# PyEphem 4.2.1 / libastro; generated by tools/gen_seasons_golden.py",
        "# year\tmarchEquinox\tjuneSolstice\tseptemberEquinox\tdecemberSolstice (UTC epoch ms)",
    ]
    for year in range(1950, 2051):
        instants = [
            ephem.next_equinox(f"{year}/3/1"),
            ephem.next_solstice(f"{year}/6/1"),
            ephem.next_equinox(f"{year}/9/1"),
            ephem.next_solstice(f"{year}/12/1"),
        ]
        lines.append("\t".join(str(v) for v in [year, *(epoch_millis(t) for t in instants)]))
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path,
        default=Path(__file__).resolve().parents[1] / "android/app/src/test/resources/seasons-golden.tsv",
    )
    parser.add_argument("--check", action="store_true", help="check that the committed vectors reproduce exactly")
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != content:
            raise SystemExit(f"vectors differ: {args.output}")
        print("seasons vectors reproduce exactly: 101 years / 404 events")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(content, encoding="utf-8")
        print(f"wrote 101 years / 404 events to {args.output}")


if __name__ == "__main__":
    main()
