#!/usr/bin/env python3
"""Independent lunar fixtures from PyEphem 4.2.1/libastro.

Run: /tmp/thinkos-venv/astro/bin/python -I tools/gen_moon_golden.py
Production uses Schlyter; this generator deliberately uses only libastro and stdlib zoneinfo.
Rise/set: geometric upper limb at -34 arcminutes, matching the USNO convention. Elevation's
horizon dip is explicit (PyEphem observer.elevation alone does not lower the horizon).
Sources: https://rhodesmill.org/pyephem/quick.html and
https://rhodesmill.org/pyephem/rise-set.html
"""
import argparse
import datetime as dt
import math
from pathlib import Path
import random
from zoneinfo import ZoneInfo

import ephem

ROOT = Path(__file__).resolve().parents[1]
UTC = dt.timezone.utc
PLACES = [
    ("Africa/Nairobi", -1.2864, 36.8172, 0),
    ("Europe/London", 51.5074, -0.1278, 0),
    ("America/New_York", 40.7128, -74.0060, 0),
    ("Australia/Sydney", -33.8688, 151.2093, 0),
    ("Europe/Oslo", 69.6492, 18.9553, 0),
    ("Atlantic/Reykjavik", 64.1466, -21.9426, 0),
    ("Arctic/Longyearbyen", 78.2232, 15.6469, 0),
    ("America/Argentina/Ushuaia", -54.8019, -68.3030, 0),
    ("Pacific/Auckland", -36.8509, 174.7645, 0),
    ("Pacific/Kiritimati", 1.8721, -157.4278, 0),
    ("Asia/Shanghai", 43.8256, 87.6168, 0),
    ("Asia/Kathmandu", 27.7172, 85.3240, 1400),
]


def millis(date):
    return round(date.datetime().replace(tzinfo=UTC).timestamp() * 1000)


def crossing_list(observer, method, start, end):
    result = []
    cursor = start
    while cursor < end:
        try:
            event = getattr(observer, method)(ephem.Moon(), start=ephem.Date(cursor), use_center=False)
        except (ephem.AlwaysUpError, ephem.NeverUpError):
            break
        instant = event.datetime().replace(tzinfo=UTC)
        if instant >= end:
            break
        result.append(str(millis(event)))
        cursor = instant + dt.timedelta(seconds=1)
    return ",".join(result) or "-"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "android/app/src/test/resources/moon-golden.tsv")
    args = parser.parse_args()
    if ephem.__version__ != "4.2.1":
        raise SystemExit("Fixtures require PyEphem 4.2.1 for reproducibility")
    rng = random.Random(20261030)
    dates = {dt.date(2026, m, d) for m, d in [(3, 20), (6, 21), (9, 23), (12, 21), (3, 8), (11, 1)]}
    dates.update(dt.date(2020, 1, 1) + dt.timedelta(days=rng.randrange(4018)) for _ in range(24))
    lines = ["# PyEphem 4.2.1/libastro; generated by tools/gen_moon_golden.py",
             "# D\tms\tzone\tlat\tlon\televation\tstart\tend\trises\tsets\taltitude\tazimuth\tillumination",
             "# P\tms\tillumination\tpreviousNew\tnextNew\tnextFirst\tnextFull\tnextLast"]
    for zone, lat, lon, elevation in PLACES:
        tz = ZoneInfo(zone)
        for date in sorted(dates):
            start = dt.datetime.combine(date, dt.time(), tzinfo=tz).astimezone(UTC)
            end = dt.datetime.combine(date + dt.timedelta(days=1), dt.time(), tzinfo=tz).astimezone(UTC)
            instant = dt.datetime.combine(date, dt.time(12), tzinfo=tz).astimezone(UTC)
            observer = ephem.Observer()
            observer.lat, observer.lon = str(lat), str(lon)
            observer.elevation = elevation
            observer.pressure = 0
            observer.horizon = str(-(34 / 60 + (1.76 / 60 * math.sqrt(elevation) if elevation > 0 else 0)))
            observer.date = instant
            moon = ephem.Moon(observer)
            alt, az, illuminated = math.degrees(moon.alt), math.degrees(moon.az), moon.phase / 100
            rises = crossing_list(observer, "next_rising", start, end)
            sets = crossing_list(observer, "next_setting", start, end)
            lines.append("\t".join(map(str, ["D", round(instant.timestamp() * 1000), zone, lat, lon,
                elevation, round(start.timestamp() * 1000), round(end.timestamp() * 1000), rises, sets,
                f"{alt:.8f}", f"{az:.8f}", f"{illuminated:.8f}"])))
    # Every other day across a full year catches perigee/apogee and all waxing/waning phases.
    for day in range(0, 366, 2):
        instant = dt.datetime(2026, 1, 1, 12, tzinfo=UTC) + dt.timedelta(days=day)
        moon = ephem.Moon(instant)
        events = [ephem.previous_new_moon, ephem.next_new_moon, ephem.next_first_quarter_moon,
                  ephem.next_full_moon, ephem.next_last_quarter_moon]
        lines.append("\t".join(map(str, ["P", round(instant.timestamp() * 1000), f"{moon.phase / 100:.8f}",
            *(millis(fn(instant)) for fn in events)])))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(lines) - 3} lunar vectors to {args.output}")


if __name__ == "__main__":
    main()
