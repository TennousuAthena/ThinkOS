#!/usr/bin/env python3
"""Prepare timezone assets; updating the privileged factory baseline requires an explicit flag."""
import argparse
import json
import hashlib
import struct
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from simulator.snapshots import make_snapshot


def timezone_data():
    """Decode the exact TZif 2+ block used by Android's TzIf (no host tzdata)."""
    source = ROOT / 'shared/tzdata'
    hashes = {}

    def read(name):
        content = (source / name).read_bytes()
        hashes[name] = hashlib.sha256(content).hexdigest()
        return content

    def rules(content):
        if content[:4] != b'TZif' or content[4] < ord('2'):
            raise ValueError('Expected TZif version 2+')

        def counts(at):
            values = struct.unpack_from('>6i', content, at + 20)
            utc, standard, leaps, transitions, types, chars = values
            if not (0 <= utc <= 256 and 0 <= standard <= 256 and 0 <= leaps <= 1000 and
                    0 <= transitions <= 20000 and 1 <= types <= 256 and 1 <= chars <= 2048):
                raise ValueError('Implausible TZif counts')
            return values

        def size(c, width):
            utc, standard, leaps, transitions, types, chars = c
            return transitions * (width + 1) + types * 6 + chars + leaps * (width + 4) + standard + utc

        at = 44 + size(counts(0), 4)
        c = counts(at)
        utc, standard, leaps, count, type_count, chars = c
        at += 44
        if at + size(c, 8) > len(content):
            raise ValueError('Truncated TZif')
        transitions = list(struct.unpack_from(f'>{count}q', content, at))
        at += count * 8
        indexes = list(content[at:at + count])
        at += count
        raw_types = [struct.unpack_from('>iBB', content, at + i * 6) for i in range(type_count)]
        at += type_count * 6
        names = content[at:at + chars]
        types = []
        for offset, dst, index in raw_types:
            if index >= chars:
                raise ValueError('Bad TZif abbreviation index')
            types.append([offset, bool(dst), names[index:].split(b'\0')[0].decode('ascii')])
        if any(i >= type_count for i in indexes) or any(a >= b for a, b in zip(transitions, transitions[1:])):
            raise ValueError('Bad TZif transitions')
        at += chars + leaps * 12 + standard + utc
        footer = content[at:].split(b'\n')[1].decode('ascii') if content[at:at + 1] == b'\n' else ''
        return [transitions, indexes, types, footer]

    version = read('VERSION').decode().strip()
    zones = {}
    for line in read('zones.tsv').decode().splitlines():
        fields = line.split('\t')
        zone, country, latitude, longitude = fields[:4]
        zones[zone] = [country, float(latitude), float(longitude), *rules(read(f'zoneinfo/{zone}'))]
    links = dict(line.split('\t') for line in read('links.tsv').decode().splitlines())
    countries = dict(line.split('\t', 1) for line in read('countries.tsv').decode().splitlines())
    data = {'version': version, 'zones': zones, 'links': links, 'countries': countries, 'sources': hashes}
    return ('// Generated by scripts/build_assets.py from shared/tzdata; do not edit. IANA tzdata is public domain.\n'
            'export type ZoneRecord = [string,number,number,number[],number[],[number,boolean,string][],string];\n'
            'export interface TzData {version:string;zones:Record<string,ZoneRecord>;links:Record<string,string>;'
            'countries:Record<string,string>;sources:Record<string,string>}\n'
            'export const TZ_DATA: TzData = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--update-factory', action='store_true', help='explicitly trust the reviewed built-in corpus')
    options = parser.parse_args()
    plugins = [make_snapshot(path, {}) for path in sorted((ROOT / 'plugins').iterdir()) if (path / 'manifest.json').is_file()]
    document = {'schema': 1, 'plugins': [{'id': p['id'], 'digest': p['digest']} for p in plugins]}
    target = ROOT / 'simulator/assets/factory-index.json'
    if options.check:
        if not target.is_file() or json.loads(target.read_text()) != document:
            raise SystemExit('Factory corpus changed. Review the plugin changes, then explicitly rebuild the asset index.')
    elif options.update_factory:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(document, indent=2) + '\n')
    elif not target.is_file():
        raise SystemExit('Missing fixed factory index. Review factory sources before --update-factory.')
    generated = ROOT / 'simulator/generated/tz-data.ts'
    timezone = timezone_data()
    if options.check:
        if not generated.is_file() or generated.read_text() != timezone:
            raise SystemExit('Bundled timezone data changed. Review shared/tzdata, then rebuild simulator assets.')
    else:
        generated.parent.mkdir(parents=True, exist_ok=True)
        generated.write_text(timezone)
    print(f'Prepared timezone assets; {len(plugins)} built-in plugins, fixed factory baseline preserved' if not options.check else f'{len(plugins)} built-in plugin digests verified')


if __name__ == '__main__':
    main()
